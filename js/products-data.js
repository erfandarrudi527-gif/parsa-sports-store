// تابع کمکی برای فرمت‌دهی قیمت به تومان
function formatPrice(price) {
  return new Intl.NumberFormat('fa-IR').format(price) + ' تومان';
}

// حل مشکل مسیر تصویر بر اساس موقعیت فایل جاری
function getCorrectImagePath(imgPath) {
  const isSubFolder = window.location.pathname.includes('/Page/') || window.location.pathname.includes('/pages/');
  if (isSubFolder) {
    return '../' + imgPath;
  }
  return './' + imgPath;
}
